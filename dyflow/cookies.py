"""Tu dong lay / lam moi cookie Douyin cho yt-dlp.

Uu tien:
1) cookies_file neu con dung
2) --cookies-from-browser (Chrome/Safari/Firefox) - tot nhat tren may local
3) Playwright mo douyin.com (fallback, can cai playwright)
"""
from __future__ import annotations
import subprocess
import sys
import time
from pathlib import Path

from .utils import log, check_tool, ytdlp_argv

# Cookie thuong con song 1-7 ngay; refresh som de tranh fail giua job
_COOKIE_MAX_AGE_SEC = 12 * 3600  # 12 gio


def cookies_stale(path: str | Path, max_age_sec: float = _COOKIE_MAX_AGE_SEC) -> bool:
    p = Path(path)
    if not p.exists() or p.stat().st_size < 50:
        return True
    age = time.time() - p.stat().st_mtime
    return age > max_age_sec


def is_cookie_error(stderr: str) -> bool:
    s = (stderr or "").lower()
    needles = (
        "fresh cookies",
        "cookies are needed",
        "cookies are required",
        "cookies (not necessarily logged in) are needed",
        "login required",
    )
    return any(n in s for n in needles)


def write_netscape_cookies(cookies: list[dict], out_path: Path) -> Path:
    """Ghi cookie dang Netscape (yt-dlp --cookies)."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Netscape HTTP Cookie File", "# Generated by dyflow"]
    for c in cookies:
        domain = c.get("domain") or ""
        if "douyin" not in domain and "bytedance" not in domain and "tiktok" not in domain:
            # van giu cookie douyin/tt; bo domain xa
            if not domain.endswith(".com") and "douyin" not in domain:
                continue
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        path = c.get("path") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        expires = int(c.get("expires") or c.get("expiry") or 0)
        if expires < 0:
            expires = 0
        name = c.get("name") or ""
        value = c.get("value") or ""
        if not name:
            continue
        lines.append(
            f"{domain}\t{include_sub}\t{path}\t{secure}\t{expires}\t{name}\t{value}"
        )
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("Da ghi cookie: %s (%d entries)", out_path, len(lines) - 2)
    return out_path


def _browser_candidates(configured: str) -> list[str]:
    """Chi khi user bat cookies_from_browser. Khong tu doan Edge/Chrome."""
    raw = (configured or "").strip().lower()
    if not raw:
        return []
    return [raw.split(":")[0]]


def refresh_from_browser(browser: str, out_path: str | Path) -> Path:
    """Lay cookie tu Chrome/Safari/Firefox bang yt-dlp --cookies-from-browser."""
    if not check_tool("yt-dlp"):
        raise RuntimeError("Chua cai yt-dlp")
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    browser = browser.strip().lower()
    log.info("Dang lay cookie tu trinh duyet: %s -> %s", browser, out_path)

    # yt-dlp se dump cookie khi co --cookies + --cookies-from-browser
    cmd = [
        *ytdlp_argv(),
        "--cookies-from-browser", browser,
        "--cookies", str(out_path),
        "--skip-download",
        "--no-warnings",
        "https://www.douyin.com/",
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if out_path.exists() and out_path.stat().st_size > 50:
        log.info("Lay cookie tu %s thanh cong", browser)
        return out_path
    err = (proc.stderr or proc.stdout or "")[-1500:]
    raise RuntimeError(
        f"Khong lay duoc cookie tu {browser}. "
        f"Mo Douyin tren {browser} 1 lan, roi thu lai.\n{err}"
    )


def refresh_with_playwright(
    out_path: str | Path,
    headless: bool = True,
    *,
    profile_dir: str | Path | None = None,
) -> Path:
    """Mo Douyin bang Playwright de lay cookie moi (khong can Chrome dang mo)."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError as e:
        raise RuntimeError(
            "Chua cai playwright. Chay:\n"
            "  pip install playwright\n"
            "  playwright install chromium"
        ) from e

    # Headed tren VPS can Xvfb (Windows dung Edge/Chrome that, khong can)
    if not headless and sys.platform != "win32":
        try:
            from .display import ensure_display
            ensure_display()
        except Exception as e:  # noqa: BLE001
            log.warning("ensure_display (cookie refresh): %s", e)

    out_path = Path(out_path)
    profile = Path(profile_dir or "./work/_chrome_dy_profile")
    profile.mkdir(parents=True, exist_ok=True)
    log.info("Dang lay cookie bang Playwright (headless=%s)...", headless)
    channels = ("msedge", "chrome") if sys.platform == "win32" else ("chrome",)
    with sync_playwright() as p:
        browser = None
        context = None
        for ch in channels:
            try:
                context = p.chromium.launch_persistent_context(
                    user_data_dir=str(profile),
                    channel=ch,
                    headless=headless,
                    locale="zh-CN",
                    args=["--disable-blink-features=AutomationControlled"],
                    viewport={"width": 1280, "height": 900},
                )
                log.info("Playwright cookie: channel=%s", ch)
                break
            except Exception as e:  # noqa: BLE001
                log.warning("Playwright %s fail: %s", ch, e)
                context = None
        if context is None:
            try:
                context = p.chromium.launch_persistent_context(
                    user_data_dir=str(profile),
                    headless=headless,
                    locale="zh-CN",
                    args=["--disable-blink-features=AutomationControlled"],
                    viewport={"width": 1280, "height": 900},
                )
            except Exception:
                browser = p.chromium.launch(headless=headless)
                context = browser.new_context(
                    locale="zh-CN",
                    user_agent=(
                        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                        "AppleWebKit/537.36 (KHTML, like Gecko) "
                        "Chrome/122.0.0.0 Safari/537.36"
                    ),
                )
        page = context.pages[0] if context.pages else context.new_page()
        page.goto("https://www.douyin.com/", wait_until="domcontentloaded", timeout=60000)
        page.wait_for_timeout(5000)
        try:
            page.mouse.wheel(0, 800)
            page.wait_for_timeout(2000)
        except Exception:  # noqa: BLE001
            pass
        cookies = context.cookies()
        context.close()
        if browser is not None:
            browser.close()

    if not cookies:
        raise RuntimeError("Playwright khong lay duoc cookie Douyin")
    return write_netscape_cookies(cookies, out_path)


def ensure_cookies(cfg: dict) -> str | None:
    """Dam bao co cookies_file. Tra ve path hoac None neu khong cau hinh.

    Cau hinh:
      cookies_file: ./cookies_douyin.txt
      cookies_from_browser: chrome   # chrome|safari|firefox|edge|""
      auto_refresh_cookies: true
      cookie_refresh_method: browser  # browser|playwright|auto
      cookie_max_age_hours: 12
    """
    cookies_file = (cfg.get("cookies_file") or "").strip()
    from_browser = (cfg.get("cookies_from_browser") or "").strip()
    auto = bool(cfg.get("auto_refresh_cookies", True))
    method = str(cfg.get("cookie_refresh_method", "auto")).lower()
    max_age = float(cfg.get("cookie_max_age_hours", 12)) * 3600

    # Khach khong bat buoc cookie. Chi dung file co san; khong lay trom Edge/Chrome.
    if not from_browser:
        if not cookies_file:
            return None
        path = Path(cookies_file)
        if path.is_file() and path.stat().st_size > 50:
            return str(path)
        return None

    if not cookies_file:
        cookies_file = "./cookies_douyin.txt"

    path = Path(cookies_file)
    need_refresh = auto and cookies_stale(path, max_age_sec=max_age)

    if not need_refresh and path.is_file() and path.stat().st_size > 50:
        return str(path)

    log.warning("Cookie het han / chua co -> tu dong lay lai...")
    errors: list[str] = []

    # 1) Chrome/Edge dang cai tren may (Windows desktop)
    if method in ("browser", "auto"):
        for browser in _browser_candidates(from_browser):
            try:
                refresh_from_browser(browser, path)
                return str(path)
            except Exception as e:  # noqa: BLE001
                errors.append(f"{browser}:{e}")
                log.warning("Lay cookie tu %s that bai: %s", browser, e)

    # 2) playwright
    if method in ("playwright", "auto"):
        try:
            # Khong bao gio mo cua so Chrome/Edge de lay cookie.
            use_headless = True
            refresh_with_playwright(
                path,
                headless=use_headless,
                profile_dir=cfg.get("chrome_profile_dir"),
            )
            return str(path)
        except Exception as e:  # noqa: BLE001
            errors.append(f"playwright:{e}")
            log.warning("Lay cookie bang Playwright that bai: %s", e)

    if path.exists() and path.stat().st_size > 50:
        log.warning("dung cookie cu (refresh fail)")
        return str(path)

    if errors:
        raise RuntimeError(
            "Khong tu dong lay duoc cookie Douyin.\n"
            + "\n".join(errors)
            + "\n\nCach thu cong: mo douyin.com tren Chrome, export cookies.txt, "
            "dat cookies_file trong config.yaml"
        )
    return str(path) if path.exists() else None


def force_refresh(cfg: dict) -> Path:
    """Bat buoc lay cookie moi (khi yt-dlp bao cookie can thiet)."""
    cookies_file = Path((cfg.get("cookies_file") or "./cookies_douyin.txt").strip())
    from_browser = (cfg.get("cookies_from_browser") or "").strip()
    method = str(cfg.get("cookie_refresh_method", "auto")).lower()

    if cookies_file.exists():
        cookies_file.unlink(missing_ok=True)

    if method in ("browser", "auto"):
        last_err: Exception | None = None
        for browser in _browser_candidates(from_browser):
            try:
                return refresh_from_browser(browser, cookies_file)
            except Exception as e:  # noqa: BLE001
                last_err = e
                log.warning("force refresh %s fail: %s", browser, e)
        if last_err:
            log.warning("force refresh browser fail: %s", last_err)

    # Khong mo cua so trinh duyet — cookie refresh luon headless.
    return refresh_with_playwright(
        cookies_file,
        headless=True,
        profile_dir=cfg.get("chrome_profile_dir"),
    )
