# Dinh dang ngay gio theo ngon ngu UI (gio local may chu)
_DT_FMT: dict[str, str] = {
    "vi": "%d/%m/%Y %H:%M",
    "en": "%b %d, %Y %I:%M %p",
    "ja": "%Y/%m/%d %H:%M",
    "pt": "%d/%m/%Y %H:%M",
    "hi": "%d/%m/%Y %H:%M",
    "de": "%d.%m.%Y %H:%M",
    "id": "%d/%m/%Y %H:%M",
    "tl": "%d/%m/%Y %I:%M %p",
}


def normalize_ui_lang(lang: str | None) -> str:
    lang = (lang or "").strip().lower()
    return lang if lang in _UI_IDS else DEFAULT_LANG


def format_datetime(lang: str | None, ts: Any) -> str:
    """Format unix timestamp theo locale UI. Rong neu ts khong hop le."""
    if ts is None or ts == "":
        return ""
    try:
        value = float(ts)
    except (TypeError, ValueError):
        return ""
    if value <= 0:
        return ""
    import time as _time

    lang = normalize_ui_lang(lang)
    fmt = _DT_FMT.get(lang) or _DT_FMT["en"]
    try:
        return _time.strftime(fmt, _time.localtime(value))
    except (OverflowError, OSError, ValueError):
        return ""


def get_ui_lang(request: Request) -> str:
    return normalize_ui_lang(request.cookies.get(COOKIE))


def t(lang: str, key: str, **kwargs: Any) -> str:
    lang = normalize_ui_lang(lang)
    text = (
        _STRINGS.get(lang, {}).get(key)
        or _STRINGS["en"].get(key)
        or _STRINGS["vi"].get(key)
        or key
    )
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def stages_for(lang: str) -> list[tuple[str, str]]:
    from .progress import STAGE_ORDER

    return [(s, t(lang, f"stage_{s}")) for s in STAGE_ORDER]


def js_bundle(lang: str) -> dict[str, str]:
    """Chuoi dung trong app.js."""
    keys = [
        "sending", "start", "no_credit", "job_create_fail", "generic_error",
        "job_failed", "job_fail_msg", "job_processing", "copied", "copy",
        "show", "hide", "approve_q", "reject_q", "password_mismatch",
        "reset_fail", "submit_tx", "preview", "preview_fail", "voice_count",
        "voice_male", "voice_female",
        "trial_verify_btn", "trial_verify_open", "trial_verify_fail",
    ]
    return {k: t(lang, k) for k in keys}


def template_globals(request: Request) -> dict[str, Any]:
    lang = get_ui_lang(request)

    def _t(key: str, **kwargs: Any) -> str:
        return t(lang, key, **kwargs)

    def _fmt_dt(ts: Any) -> str:
        return format_datetime(lang, ts)

    return {
        "ui_lang": lang,
        "ui_languages": UI_LANGUAGES,
        "t": _t,
        "fmt_dt": _fmt_dt,
        "i18n_js": js_bundle(lang),
    }
